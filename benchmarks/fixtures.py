"""Generates the graph modules the benchmark scenarios build and run, and their oracles.

Every generator here is deterministic: the same parameters give the same source text on every
Python version, so a scenario's fixture can be fingerprinted and frozen. Each oracle computes the
expected outputs from the parameters alone, without Hamilton and without the generated code, so a
scenario that returns wrong results fails its check instead of producing a fast number.

This module imports only the standard library: the controller imports it in any interpreter.
"""

from __future__ import annotations

import dataclasses
import hashlib
import importlib.util
import sys
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import pathlib
    import types

# Values stay below this prime so that every node returns a small int.
MODULUS = 1_000_003


@dataclasses.dataclass(frozen=True)
class LayeredGraph:
    """A graph of integer nodes in ``layers`` layers of ``width`` nodes each.

    The nodes of layer 0 take the external input ``x``. Node ``j`` of each later layer depends on
    node ``j`` of the previous layer, which keeps every node upstream of the last layer, and on up
    to two more nodes of the previous layer, chosen by arithmetic on the indexes. The depth of the
    graph is ``layers``, so the recursive 1.x execution stays far from the recursion limit.
    """

    layers: int
    width: int

    def __post_init__(self) -> None:
        if self.layers < 1 or self.width < 1:
            raise ValueError(f"A layered graph needs at least one layer and one node: {self}")

    @property
    def node_count(self) -> int:
        return self.layers * self.width

    @staticmethod
    def name(layer: int, index: int) -> str:
        return f"n{layer}_{index}"

    def dependencies(self, layer: int, index: int) -> tuple[int, ...]:
        """Indexes in layer ``layer - 1`` that node ``index`` of ``layer`` depends on."""
        if layer == 0:
            return ()
        extra = (layer * 31 + index * 17) % 3  # 0, 1 or 2 more dependencies
        chosen = [index]
        for k in range(1, extra + 1):
            candidate = index + 1 + (layer * 131 + index * 71 + k * 37) % max(self.width - 1, 1)
            candidate %= self.width
            if candidate not in chosen:
                chosen.append(candidate)
        return tuple(chosen)

    def final_nodes(self) -> list[str]:
        return [self.name(self.layers - 1, j) for j in range(self.width)]

    def source(self) -> str:
        lines = [
            '"""Generated by benchmarks/fixtures.py; do not edit."""',
            "",
        ]
        for j in range(self.width):
            lines += [
                "",
                f"def {self.name(0, j)}(x: int) -> int:",
                f"    return (x * {j + 1} + {j}) % {MODULUS}",
                "",
            ]
        for i in range(1, self.layers):
            for j in range(self.width):
                deps = [self.name(i - 1, d) for d in self.dependencies(i, j)]
                params = ", ".join(f"{d}: int" for d in deps)
                terms = " + ".join(f"{k + 1} * {d}" for k, d in enumerate(deps))
                lines += [
                    "",
                    f"def {self.name(i, j)}({params}) -> int:",
                    f"    return ({terms} + {j}) % {MODULUS}",
                    "",
                ]
        return "\n".join(lines)

    def oracle(self, x: int) -> dict[str, int]:
        """The value of every final node for input ``x``, computed from the parameters alone."""
        previous = [(x * (j + 1) + j) % MODULUS for j in range(self.width)]
        for i in range(1, self.layers):
            current = []
            for j in range(self.width):
                deps = self.dependencies(i, j)
                total = sum((k + 1) * previous[d] for k, d in enumerate(deps))
                current.append((total + j) % MODULUS)
            previous = current
        return {self.name(self.layers - 1, j): previous[j] for j in range(self.width)}


# The CPU workload of the 2.0 outline: identical pure-Python integer kernels with distinct inputs.
KERNEL_SOURCE = """
def _kernel(item: int, iterations: int) -> int:
    total = 0
    for i in range(iterations):
        total += (i ^ item) & 255
    return total + item
"""


def kernel_reference(item: int, iterations: int) -> int:
    """The kernel's result in closed form: every full block of 256 sums 0..255 once."""
    blocks, tail = divmod(iterations, 256)
    return blocks * 32640 + sum((i ^ item) & 255 for i in range(tail)) + item


@dataclasses.dataclass(frozen=True)
class CpuWorkload:
    """``items`` kernels of ``iterations`` iterations each, one distinct item ID per kernel."""

    items: tuple[int, ...]
    iterations: int

    def __post_init__(self) -> None:
        if len(set(self.items)) != len(self.items):
            raise ValueError(f"Item IDs must be distinct: {self.items}")

    def sequential_source(self) -> str:
        """One node per item and one node that collects their outputs in item order."""
        lines = ['"""Generated by benchmarks/fixtures.py; do not edit."""', "", KERNEL_SOURCE]
        for item in self.items:
            lines += [
                "",
                f"def item_{item}(iterations: int) -> int:",
                f"    return _kernel({item}, iterations)",
                "",
            ]
        params = ", ".join(f"item_{item}: int" for item in self.items)
        values = ", ".join(f"item_{item}" for item in self.items)
        lines += [
            "",
            f"def results({params}) -> list[int]:",
            f"    return [{values}]",
            "",
        ]
        return "\n".join(lines)

    def mapped_source(self) -> str:
        """Expands the item IDs, applies the kernel to each and collects the outputs."""
        return "\n".join(
            [
                '"""Generated by benchmarks/fixtures.py; do not edit."""',
                "",
                "from hamilton.htypes import Collect, Parallelizable",
                "",
                KERNEL_SOURCE,
                "",
                "def item_id() -> Parallelizable[int]:",
                f"    yield from {self.items!r}",
                "",
                "",
                "def kernel_output(item_id: int, iterations: int) -> int:",
                "    return _kernel(item_id, iterations)",
                "",
                "",
                "def results(kernel_output: Collect[int]) -> list[int]:",
                "    return list(kernel_output)",
                "",
            ]
        )

    def oracle(self) -> list[int]:
        return [kernel_reference(item, self.iterations) for item in self.items]


def digest(source: str) -> str:
    return hashlib.sha256(source.encode()).hexdigest()


def load_module(directory: pathlib.Path, name: str, source: str) -> types.ModuleType:
    """Writes ``source`` to ``directory/name.py`` and imports it as the module ``name``.

    The module goes into ``sys.modules`` so that tools which look a function's module up by name
    find it, as they would for a module of a user's project.
    """
    path = directory / f"{name}.py"
    path.write_text(source)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load the generated module {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module
